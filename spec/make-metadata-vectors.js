'use strict';
// Writes spec/metadata-vectors.json: photos with metadata (base64), the options, and exactly what the JavaScript readMetadata / stripMetadata
// answer, including the stripped file byte for byte. The .NET port must produce the same bytes (dotnet/.../MetadataTests.cs).
// Run: node spec/make-metadata-vectors.js
const fs = require('fs');
const path = require('path');
const FV = require('../src/fileValidator.js');
const img = require('../tests/helpers/images.js');

const cases = [];
const add = (id, bytes, name, type, options) => cases.push({ id, bytes, name, type, options: options || {} });

// JPEG
add('jpeg: clean', img.jpeg(), 'a.jpg', 'image/jpeg');
add('jpeg: exif orientation 1 only', img.jpeg({ exif: true, orientation: 1 }), 'a.jpg', 'image/jpeg');
add('jpeg: exif orientation 6 and gps', img.jpeg({ exif: true, orientation: 6, gps: true }), 'a.jpg', 'image/jpeg');
add('jpeg: exif orientation 8 no gps', img.jpeg({ exif: true, orientation: 8 }), 'a.jpg', 'image/jpeg');
add('jpeg: exif without orientation, with gps', img.jpeg({ exif: true, gps: true }), 'a.jpg', 'image/jpeg');
add('jpeg: everything', img.jpeg({ exif: true, orientation: 3, gps: true, xmp: true, iptc: true, comment: true, icc: true }), 'a.jpg', 'image/jpeg');
add('jpeg: xmp only', img.jpeg({ xmp: true }), 'a.jpg', 'image/jpeg');
add('jpeg: iptc only', img.jpeg({ iptc: true }), 'a.jpg', 'image/jpeg');
add('jpeg: comment only', img.jpeg({ comment: true }), 'a.jpg', 'image/jpeg');
add('jpeg: icc only is kept', img.jpeg({ icc: true }), 'a.jpg', 'image/jpeg');
add('jpeg: icc dropped on request', img.jpeg({ exif: true, orientation: 6, icc: true }), 'a.jpg', 'image/jpeg', { keepColorProfile: false });
add('jpeg: orientation dropped on request', img.jpeg({ exif: true, orientation: 6, gps: true }), 'a.jpg', 'image/jpeg', { keepOrientation: false });
add('jpeg: broken segment length', img.cat([0xff, 0xd8, 0xff, 0xe1, 0xff, 0xff], new Array(10).fill(1)), 'a.jpg', 'image/jpeg');
add('jpeg: no scan', img.cat([0xff, 0xd8], img.seg(0xe0, img.cat(img.ascii('JFIF\0'), [1, 1, 0, 0, 1, 0, 1, 0, 0]))), 'a.jpg', 'image/jpeg');
// PNG
add('png: clean', img.png(), 'a.png', 'image/png');
add('png: text and time', img.png({ text: true, time: true }), 'a.png', 'image/png');
add('png: exif orientation 8 and gps', img.png({ exif: true, orientation: 8, gps: true }), 'a.png', 'image/png');
add('png: exif orientation 1', img.png({ exif: true, orientation: 1 }), 'a.png', 'image/png');
add('png: everything', img.png({ exif: true, orientation: 6, gps: true, text: true, xmp: true, time: true }), 'a.png', 'image/png');
add('png: orientation dropped on request', img.png({ exif: true, orientation: 6, gps: true }), 'a.png', 'image/png', { keepOrientation: false });
add('png: cut off', img.png({ text: true }).slice(0, 60), 'a.png', 'image/png');
// WebP
add('webp: clean', img.webp(), 'a.webp', 'image/webp');
add('webp: exif orientation 3 and gps and xmp', img.webp({ exif: true, orientation: 3, gps: true, xmp: true }), 'a.webp', 'image/webp');
add('webp: xmp only', img.webp({ xmp: true }), 'a.webp', 'image/webp');
add('webp: exif orientation 1', img.webp({ exif: true, orientation: 1 }), 'a.webp', 'image/webp');
add('webp: orientation dropped on request', img.webp({ exif: true, orientation: 3, gps: true }), 'a.webp', 'image/webp', { keepOrientation: false });
// not photos
add('text file', new TextEncoder().encode('hello'), 'a.txt', 'text/plain');
add('empty file', new Uint8Array(0), 'a.jpg', 'image/jpeg');

async function build() {
    const out = [];
    for (const c of cases) {
        const file = new File([c.bytes], c.name, { type: c.type });
        const before = await FV.readMetadata(file, c.options);
        const stripped = await FV.stripMetadata(file, c.options);
        const changed = stripped !== file;
        const after = changed ? await FV.readMetadata(stripped, c.options) : before;
        out.push({
            id: c.id,
            base64: Buffer.from(c.bytes).toString('base64'),
            options: c.options,
            before,
            changed,
            removed: changed ? stripped.fvStripped.removed : [],
            output: changed ? Buffer.from(await stripped.arrayBuffer()).toString('base64') : null,
            after
        });
    }
    return out;
}

module.exports = { build };
if (require.main === module) {
    build().then(cs => {
        fs.writeFileSync(path.join(__dirname, 'metadata-vectors.json'), JSON.stringify({ comment: 'Generated by spec/make-metadata-vectors.js from the JavaScript FileValidator. Do not edit.', cases: cs }, null, 1) + '\n');
        console.log(cs.length + ' cases (' + cs.filter(c => c.changed).length + ' changed)');
    });
}
