'use strict';
// Writes dotnet/FormAndFileValidator/FileTables.g.cs from the JavaScript FileValidator, so the .NET port knows exactly the same
// extensions, MIME types, dangerous lists and message templates. Run: node spec/make-file-tables.js   (npm test checks that the file is current).
const fs = require('fs');
const path = require('path');
const FV = require('../src/fileValidator.js');

const q = s => JSON.stringify(String(s));          // a C# string literal for plain text (no characters that need \u escapes)
const list = a => '{ ' + a.map(q).join(', ') + ' }';

function generate() {
    const c = FV.constants;
    const ext = c.EXTENSIONS();
    let o = '// <auto-generated>\n// Generated by spec/make-file-tables.js from src/fileValidator.js. Do not edit: run `node spec/make-file-tables.js`.\n// </auto-generated>\n';
    o += 'using System.Collections.Generic;\n\nnamespace FormAndFileValidator\n{\n    internal static class FileTables\n    {\n';
    o += '        internal static readonly string[] DangerousExtensions = new[] ' + list(c.DEFAULT_DANGEROUS_EXTENSIONS) + ';\n\n';
    o += '        internal static readonly string[] DangerousMimeTypes = new[] ' + list(c.DEFAULT_DANGEROUS_MIME_TYPES) + ';\n\n';
    o += '        /// <summary>Extension -> the MIME types that may be reported for it (the first one is the primary type).</summary>\n';
    o += '        internal static readonly Dictionary<string, string[]> Extensions = new Dictionary<string, string[]>\n        {\n';
    for (const k of Object.keys(ext)) o += '            [' + q(k) + '] = new[] ' + list(ext[k]) + ',\n';
    o += '        };\n\n';
    o += '        /// <summary>The English message templates, {placeholders} are filled from the issue parameters.</summary>\n';
    o += '        internal static readonly Dictionary<string, string> Messages = new Dictionary<string, string>\n        {\n';
    for (const k of Object.keys(FV.defaultMessages)) o += '            [' + q(k) + '] = ' + q(FV.defaultMessages[k]) + ',\n';
    o += '        };\n\n';
    o += '        /// <summary>The signature names, in the order they are tested (a test keeps the C# list identical).</summary>\n';
    o += '        internal static readonly string[] SignatureNames = new[] ' + list(c.SIGNATURES.map(s => s.name)) + ';\n';
    o += '    }\n}\n';
    return o;
}

const file = path.join(__dirname, '..', 'dotnet', 'FormAndFileValidator', 'FileTables.g.cs');
module.exports = { generate, file };
if (require.main === module) { fs.writeFileSync(file, generate().replace(/\n/g, '\r\n')); console.log('wrote ' + path.relative(process.cwd(), file)); }
